import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { IDENTITY_ERROR_CODES, IdentityError, RETRYABLE_IDENTITY_ERRORS, createPkcePair, exchangeIdentityCode, verifyIdentity } from "./identity.js";

describe("the redirect flow", () => {
  it("makes a fresh PKCE pair whose challenge is the verifier's base64url SHA-256", async () => {
    const { verifier, challenge } = await createPkcePair();
    expect(verifier).toMatch(/^[A-Za-z0-9_-]{43}$/);
    expect(challenge).toBe(createHash("sha256").update(verifier).digest("base64url"));
    expect((await createPkcePair()).verifier).not.toBe(verifier);
  });

  it("exchanges a code with the app key in its header, and throws the API's error code", async () => {
    let seen: Request | undefined;
    const result = await exchangeIdentityCode({
      baseUrl: "http://api.invalid",
      appKey: "yfa_key",
      code: "yfic_code",
      redirectUri: "https://arcade.example/callback",
      codeVerifier: "v".repeat(43),
      fetch: async (input) => {
        seen = input as Request;
        return Response.json({ identity: { accountId: "a" }, app: { id: "x", name: "X" }, verifiedAt: "2026-10-26T00:00:00.000Z" });
      },
    });
    expect(seen?.url).toBe("http://api.invalid/v1/identity/exchange");
    expect(seen?.headers.get("yakfeed-app-key")).toBe("yfa_key");
    expect(await seen?.json()).toEqual({ code: "yfic_code", redirectUri: "https://arcade.example/callback", codeVerifier: "v".repeat(43) });
    expect(result.identity.accountId).toBe("a");

    const refused = exchangeIdentityCode({
      baseUrl: "http://api.invalid",
      appKey: "yfa_key",
      code: "yfic_code",
      redirectUri: "https://arcade.example/callback",
      codeVerifier: "v".repeat(43),
      fetch: async () => Response.json({ error: "invalid_code_verifier", message: "no" }, { status: 400 }),
    });
    await expect(refused).rejects.toMatchObject({ code: "invalid_code_verifier", status: 400 });
  });
});

describe("verifyIdentity", () => {
  it("sends the app key in its header and the token in the body", async () => {
    let seen: Request | undefined;
    const result = await verifyIdentity({
      baseUrl: "http://api.invalid",
      appKey: "yfa_key",
      token: "yfid_token",
      fetch: async (input) => {
        seen = input as Request;
        return Response.json({ identity: { accountId: "a" }, app: { id: "x", name: "X" }, verifiedAt: "2026-10-24T00:00:00.000Z" });
      },
    });
    expect(seen?.url).toBe("http://api.invalid/v1/identity/verify");
    expect(seen?.headers.get("yakfeed-app-key")).toBe("yfa_key");
    expect(seen?.headers.get("authorization")).toBeNull();
    expect(await seen?.json()).toEqual({ token: "yfid_token" });
    expect(result.app.name).toBe("X");
  });

  it("throws the API's error code", async () => {
    const refused = () =>
      verifyIdentity({ baseUrl: "http://api.invalid", appKey: "yfa_key", token: "yfid_token", fetch: async () => Response.json({ error: "token_expired", message: "expired" }, { status: 400 }) });
    await expect(refused()).rejects.toBeInstanceOf(IdentityError);
    await expect(refused()).rejects.toMatchObject({ code: "token_expired", status: 400, message: "expired" });
  });
});

// The error contract: IdentityErrorCode holds exactly the codes the
// API's OpenAPI document lists for verifying and exchanging (regenerated by `pnpm sdk`), plus the
// SDK's own `http_error`.
const openapi = JSON.parse(readFileSync(new URL("../openapi.json", import.meta.url), "utf8")) as {
  components: { schemas: Record<string, { properties: { error: { enum: string[] } } }> };
};

describe("IdentityErrorCode", () => {
  it("is every code the API lists for verify and exchange, and nothing else", () => {
    const api = new Set([...openapi.components.schemas.IdentityVerifyError!.properties.error.enum, ...openapi.components.schemas.IdentityExchangeError!.properties.error.enum]);
    expect(IDENTITY_ERROR_CODES.filter((c) => c !== "http_error").sort()).toEqual([...api].sort());
  });

  it("says which failures are worth another try, and keeps retryAfter", async () => {
    const answer = (status: number, body: unknown, headers: Record<string, string> = {}) =>
      verifyIdentity({ baseUrl: "http://api.invalid", appKey: "yfa_key", token: "yfid_token", fetch: async () => Response.json(body, { status, headers }) }).catch((e: unknown) => e as IdentityError);
    expect(await answer(429, { error: "rate_limited", message: "slow down", retryAfter: 7 }, { "retry-after": "7" })).toMatchObject({ code: "rate_limited", retryable: true, retryAfter: 7 });
    expect(await answer(500, { error: "internal_error", message: "Something went wrong." })).toMatchObject({ retryable: true });
    expect(await answer(400, { error: "token_used", message: "used" })).toMatchObject({ retryable: false });
    expect(await answer(400, { error: "invalid_request", message: "body/token" })).toMatchObject({ retryable: false });
    // Not yakfeed's JSON: a proxy in the way.
    const proxy = await verifyIdentity({ baseUrl: "http://api.invalid", appKey: "k", token: "t", fetch: async () => new Response("Bad Gateway", { status: 502 }) }).catch((e: unknown) => e as IdentityError);
    expect(proxy).toMatchObject({ code: "http_error", status: 502, retryable: true });
    for (const code of RETRYABLE_IDENTITY_ERRORS) expect(IDENTITY_ERROR_CODES).toContain(code);
  });
});
